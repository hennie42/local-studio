#!/usr/bin/env python3
"""gen-config.py: generate local-model configs from models/catalog.json + a hardware profile.

  gen-config.py llama-swap PROFILE [-o FILE]   llama-swap config (default: ~/.config/llama-swap/config.yaml)
  gen-config.py downloads  PROFILE             "repo file [local-name]" lines for models/download.sh
  gen-config.py opencode   PROFILE [-o FILE]   OpenCode provider config for the same models
  gen-config.py effective  PROFILE [-o FILE]   the profile's models after overrides (ctx, vision) as JSON;
                                               install.sh writes it to ~/.config/studio/models.json
  gen-config.py list                           profiles and models

PROFILE is a name in models/profiles/ (e.g. 16gb-worker) or a path. GPU indices come from the studio config
(STUDIO_WORKER_GPU, STUDIO_SMALL_GPU), so a profile only says which models go on which GPU.
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "lib"))
from studio_config import cfg  # noqa: E402

CATALOG = json.loads((HERE / "catalog.json").read_text())


def profile(name):
    p = pathlib.Path(name)
    if not p.exists():
        p = HERE / "profiles" / f"{name}.json"
    d = json.loads(p.read_text())
    d["_name"] = p.stem
    return d


def model(mid, prof):
    m = dict(CATALOG["models"][mid])
    m.update(prof.get("overrides", {}).get(mid, {}))
    return m


def cmd_lines(mid, m):
    lines = [f"${{{m['server']}-server}} ${{common}}", f"-m ${{models}}/{m['model']}"]
    if m.get("mmproj"):
        lines.append(f"--mmproj ${{models}}/{m['mmproj']}" + ("" if m.get("mmproj_offload", True) else " --no-mmproj-offload"))
    if m.get("n_cpu_moe"):
        lines.append(f"--n-cpu-moe {m['n_cpu_moe']}")
    a = m["args"].split(" --temp", 1)
    lines.append(a[0])
    if len(a) > 1:
        lines.append("--temp" + a[1])
    if m.get("chat_template"):
        lines.append(f"--chat-template-file {HERE / 'templates' / m['chat_template']}")
    if m.get("chat_template_kwargs"):
        lines.append(f"--chat-template-kwargs '{json.dumps(m['chat_template_kwargs'], separators=(',', ':'))}'")
    lines.append(f"--alias {mid}")
    return lines


def llama_swap(prof):
    big_gpu, small_gpu = cfg["STUDIO_WORKER_GPU"], cfg.get("STUDIO_SMALL_GPU", "")
    out = [f"# Generated by models/gen-config.py from models/catalog.json + profile '{prof['_name']}': edit those, then",
           "# regenerate (install.sh does it). One OpenAI + Anthropic compatible endpoint on 127.0.0.1:8080.",
           "# GPU indices follow nvidia-smi (CUDA_DEVICE_ORDER=PCI_BUS_ID) and come from ~/.config/studio/studio.env.",
           "", "healthCheckTimeout: 300", "logLevel: info", "startPort: 10001",
           "# Unload idle models after 1 hour to free the GPUs; the next request reloads them.", "globalTTL: 3600", "",
           "macros:", f"  \"models\": \"{cfg['STUDIO_MODELS_DIR']}\""]
    servers = {model(m, prof)["server"] for m in prof.get("big", []) + prof.get("small", [])}
    for s in sorted(servers):
        out.append(f"  \"{s}-server\": \"{CATALOG['servers'][s]}\"")
    out += [f"  \"common\": \"{CATALOG['common']}\"", "", "models:"]
    for slot, gpu in (("big", big_gpu), ("small", small_gpu)):
        for mid in prof.get(slot, []):
            m = model(mid, prof)
            out += [f"  \"{mid}\":", f"    name: \"{m['name']}\"", "    env:", "      - \"CUDA_DEVICE_ORDER=PCI_BUS_ID\"",
                    f"      - \"CUDA_VISIBLE_DEVICES={gpu}\""]
            out += [f"    # {n}" for n in m.get("notes", [])]
            out += ["    cmd: |"] + [f"      {line}" for line in cmd_lines(mid, m)] + [""]
    out += ["routing:", "  router:", "    use: group", "    settings:", "      groups:",
            "        # worker GPU: one big model at a time", "        \"big\":", "          swap: true",
            "          exclusive: false", "          members:"] + [f"            - \"{m}\"" for m in prof.get("big", [])]
    if prof.get("small"):
        out += ["        # second GPU: one small model at a time, never unloaded by the big group", "        \"small\":",
                "          persistent: true", "          swap: true", "          exclusive: false", "          members:"]
        out += [f"            - \"{m}\"" for m in prof["small"]]
    if prof.get("preload"):
        out += ["", "hooks:", "  on_startup:", "    preload:"] + [f"      - \"{m}\"" for m in prof["preload"]]
    return "\n".join(out) + "\n"


def downloads(prof):
    lines = []
    for mid in prof.get("big", []) + prof.get("small", []):
        for f in model(mid, prof).get("files", []):
            lines.append(" ".join(f))
    return "\n".join(dict.fromkeys(lines)) + "\n"


def opencode(prof):
    models = {}
    for mid in prof.get("big", []) + prof.get("small", []):
        m = model(mid, prof)
        models[mid] = {"name": m["name"], "tool_call": True, "reasoning": True,
                       "limit": {"context": m["ctx"], "output": min(32768, m["ctx"] // 4)},
                       "modalities": {"input": ["text", "image"] if m.get("vision") else ["text"], "output": ["text"]},
                       "attachment": bool(m.get("vision"))}
    big, small = prof.get("big", []), prof.get("small", [])
    worker = prof.get("routing", {}).get("worker", {}).get("model")
    default = worker if worker in big else (big[0] if big else None)   # the routing worker when it is local
    d = {"$schema": "https://opencode.ai/config.json", "model": f"local/{default}" if default else None,
         "small_model": f"local/{small[0] if small else big[0]}" if big else None,
         "provider": {"local": {"npm": "@ai-sdk/openai-compatible", "name": "llama-swap (local)",
                                "options": {"baseURL": cfg["STUDIO_LLAMA_URL"].rstrip("/") + "/v1"}, "models": models}}}
    return json.dumps(d, indent=2) + "\n"


def effective(prof):
    ids = prof.get("big", []) + prof.get("small", [])
    return json.dumps({"profile": prof["_name"], "models": {m: model(m, prof) for m in ids}}, indent=1) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["llama-swap", "downloads", "opencode", "effective", "list"])
    ap.add_argument("profile", nargs="?")
    ap.add_argument("-o", "--out")
    a = ap.parse_args()
    if a.what == "list":
        for p in sorted((HERE / "profiles").glob("*.json")):
            print(f"{p.stem:28} {json.loads(p.read_text())['description']}")
        print()
        for mid, m in CATALOG["models"].items():
            print(f"{mid:18} {m['slot']:5} {m.get('vram_gb', '?'):>3} GB  {m.get('tested', '')[:90]}")
        return
    prof = profile(a.profile)
    text = {"llama-swap": llama_swap, "downloads": downloads, "opencode": opencode, "effective": effective}[a.what](prof)
    if a.out:
        out = pathlib.Path(a.out).expanduser()
        out.parent.mkdir(parents=True, exist_ok=True)
        if out.is_symlink():   # e.g. a link into a repo from an older setup: never write through it
            out.unlink()
        out.write_text(text)
        print(f"wrote {a.out}")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
